SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE DATABASE IF NOT EXISTS `mgmp_online` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE `mgmp_online`;

DROP TABLE IF EXISTS `kas`, `iuran`, `materi`, `peserta`, `kegiatan`, `pengumuman`, `anggota`, `pengaturan`;

-- Identitas MGMP (satu baris, id = 1)
CREATE TABLE `pengaturan` (
  `id` TINYINT UNSIGNED NOT NULL PRIMARY KEY,
  `nama` VARCHAR(120) NOT NULL,
  `mapel` VARCHAR(60) NOT NULL,
  `jenjang` VARCHAR(20) NOT NULL,
  `wilayah` VARCHAR(80) NOT NULL,
  `sekretariat` VARCHAR(200) DEFAULT NULL,
  `telepon` VARCHAR(30) DEFAULT NULL,
  `email` VARCHAR(120) DEFAULT NULL,
  `whatsapp` VARCHAR(20) DEFAULT NULL,
  `ketua` VARCHAR(100) DEFAULT NULL,
  `sekretaris` VARCHAR(100) DEFAULT NULL,
  `bendahara` VARCHAR(100) DEFAULT NULL,
  `pembina` VARCHAR(100) DEFAULT NULL,
  `periode` VARCHAR(20) DEFAULT NULL,
  `iuran_bulanan` INT UNSIGNED NOT NULL DEFAULT 0,
  `menit_presensi` SMALLINT UNSIGNED NOT NULL DEFAULT 120,
  `tagline` VARCHAR(160) DEFAULT NULL,
  `tentang` TEXT,
  `logo` VARCHAR(120) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Guru anggota MGMP; pengurus memakai tabel yang sama dengan kolom role
CREATE TABLE `anggota` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `nuptk` VARCHAR(20) DEFAULT NULL,
  `nama` VARCHAR(100) NOT NULL,
  `email` VARCHAR(120) NOT NULL UNIQUE,
  `password` VARCHAR(255) NOT NULL,
  `no_hp` VARCHAR(20) DEFAULT NULL,
  `sekolah` VARCHAR(120) NOT NULL,
  `kecamatan` VARCHAR(60) DEFAULT NULL,
  `jabatan` VARCHAR(40) DEFAULT 'Guru Mata Pelajaran',
  `role` ENUM('ketua','sekretaris','bendahara','anggota') NOT NULL DEFAULT 'anggota',
  `status` ENUM('pending','aktif','nonaktif') NOT NULL DEFAULT 'pending',
  `catatan` VARCHAR(200) DEFAULT NULL,
  `created_at` DATETIME NOT NULL,
  KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Kegiatan MGMP: rapat rutin, workshop, IHT, diklat, lomba
CREATE TABLE `kegiatan` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `judul` VARCHAR(150) NOT NULL,
  `jenis` ENUM('rutin','workshop','iht','diklat','lomba','rapat') NOT NULL DEFAULT 'rutin',
  `tanggal` DATE NOT NULL,
  `jam_mulai` TIME NOT NULL DEFAULT '08:00:00',
  `jam_selesai` TIME NOT NULL DEFAULT '12:00:00',
  `tempat` VARCHAR(150) NOT NULL,
  `narasumber` VARCHAR(120) DEFAULT NULL,
  `kuota` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `biaya` INT UNSIGNED NOT NULL DEFAULT 0,
  `jam_pelatihan` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `deskripsi` TEXT,
  `status` ENUM('rencana','dibuka','selesai','batal') NOT NULL DEFAULT 'rencana',
  `kode_presensi` VARCHAR(8) DEFAULT NULL,
  `presensi_tutup` DATETIME DEFAULT NULL,
  `dibuat_oleh` INT UNSIGNED DEFAULT NULL,
  `created_at` DATETIME NOT NULL,
  KEY `idx_tanggal` (`tanggal`),
  CONSTRAINT `fk_keg_user` FOREIGN KEY (`dibuat_oleh`) REFERENCES `anggota` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Pendaftaran & kehadiran peserta kegiatan
CREATE TABLE `peserta` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `kegiatan_id` INT UNSIGNED NOT NULL,
  `anggota_id` INT UNSIGNED NOT NULL,
  `daftar_at` DATETIME NOT NULL,
  `hadir_at` DATETIME DEFAULT NULL,
  `status` ENUM('terdaftar','hadir','izin','alfa') NOT NULL DEFAULT 'terdaftar',
  `catatan` VARCHAR(200) DEFAULT NULL,
  `no_sertifikat` VARCHAR(40) DEFAULT NULL,
  `kode_verifikasi` VARCHAR(12) DEFAULT NULL,
  UNIQUE KEY `uq_peserta` (`kegiatan_id`, `anggota_id`),
  UNIQUE KEY `uq_kode` (`kode_verifikasi`),
  CONSTRAINT `fk_ps_keg` FOREIGN KEY (`kegiatan_id`) REFERENCES `kegiatan` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_ps_ang` FOREIGN KEY (`anggota_id`) REFERENCES `anggota` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Bank materi / perangkat pembelajaran yang dibagikan anggota
CREATE TABLE `materi` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `judul` VARCHAR(150) NOT NULL,
  `kategori` ENUM('perangkat','modul','soal','media','regulasi','lainnya') NOT NULL DEFAULT 'perangkat',
  `kelas` VARCHAR(20) DEFAULT NULL,
  `deskripsi` TEXT,
  `file` VARCHAR(160) NOT NULL,
  `nama_asli` VARCHAR(160) NOT NULL,
  `ukuran` INT UNSIGNED NOT NULL DEFAULT 0,
  `anggota_id` INT UNSIGNED DEFAULT NULL,
  `kegiatan_id` INT UNSIGNED DEFAULT NULL,
  `status` ENUM('menunggu','disetujui','ditolak') NOT NULL DEFAULT 'menunggu',
  `publik` TINYINT(1) NOT NULL DEFAULT 0,
  `catatan` VARCHAR(200) DEFAULT NULL,
  `unduhan` INT UNSIGNED NOT NULL DEFAULT 0,
  `created_at` DATETIME NOT NULL,
  KEY `idx_status` (`status`),
  CONSTRAINT `fk_mt_ang` FOREIGN KEY (`anggota_id`) REFERENCES `anggota` (`id`) ON DELETE SET NULL,
  CONSTRAINT `fk_mt_keg` FOREIGN KEY (`kegiatan_id`) REFERENCES `kegiatan` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Tagihan iuran anggota per periode (YYYY-MM)
CREATE TABLE `iuran` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `anggota_id` INT UNSIGNED NOT NULL,
  `periode` CHAR(7) NOT NULL,
  `jumlah` INT UNSIGNED NOT NULL,
  `status` ENUM('belum','lunas') NOT NULL DEFAULT 'belum',
  `dibayar_at` DATETIME DEFAULT NULL,
  `metode` VARCHAR(20) DEFAULT NULL,
  `dicatat_oleh` INT UNSIGNED DEFAULT NULL,
  `catatan` VARCHAR(150) DEFAULT NULL,
  UNIQUE KEY `uq_iuran` (`anggota_id`, `periode`),
  CONSTRAINT `fk_iu_ang` FOREIGN KEY (`anggota_id`) REFERENCES `anggota` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Buku kas MGMP; pembayaran iuran otomatis tercatat di sini
CREATE TABLE `kas` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `tanggal` DATE NOT NULL,
  `jenis` ENUM('masuk','keluar') NOT NULL,
  `kategori` VARCHAR(40) NOT NULL,
  `jumlah` INT UNSIGNED NOT NULL,
  `keterangan` VARCHAR(200) DEFAULT NULL,
  `iuran_id` INT UNSIGNED DEFAULT NULL,
  `dicatat_oleh` INT UNSIGNED DEFAULT NULL,
  `created_at` DATETIME NOT NULL,
  KEY `idx_tanggal` (`tanggal`),
  CONSTRAINT `fk_kas_iuran` FOREIGN KEY (`iuran_id`) REFERENCES `iuran` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `pengumuman` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `judul` VARCHAR(150) NOT NULL,
  `isi` TEXT NOT NULL,
  `penting` TINYINT(1) NOT NULL DEFAULT 0,
  `publik` TINYINT(1) NOT NULL DEFAULT 1,
  `dibuat_oleh` INT UNSIGNED DEFAULT NULL,
  `created_at` DATETIME NOT NULL,
  CONSTRAINT `fk_pg_ang` FOREIGN KEY (`dibuat_oleh`) REFERENCES `anggota` (`id`) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;

